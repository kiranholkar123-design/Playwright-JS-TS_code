/**
 * modules operator will return the remainder left after the dividing one number by other
 */

console.log(40 % 2); // 0

console.log(41 % 3); // 2

console.log(-44 % 5); // -4 = sign follos the dividend not divisor

console.log(-45 % 5); // -0 =  sign follos the dividend

console.log(-43 % -5); // -3

console.log(43 % -5); // 3 = sign follos the dividend not divisor

console.log(33.5 % 3); //0.5


